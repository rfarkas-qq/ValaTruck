import fs from "fs";
import path from "path";
import yaml from "yaml";

const tracksDir = path.join(process.cwd(), "src", "data", "tracks");
const outputFile = path.join(process.cwd(), "src", "data", "tracks.ts");

if (!fs.existsSync(tracksDir)) {
  fs.mkdirSync(tracksDir, { recursive: true });
}

const files = fs.readdirSync(tracksDir).filter((file) => file.endsWith(".yaml") || file.endsWith(".yml"));
const allTracks = [];

for (const file of files) {
  const filePath = path.join(tracksDir, file);
  const content = fs.readFileSync(filePath, "utf8");
  const rawList = yaml.parse(content);

  if (Array.isArray(rawList)) {
    for (const item of rawList) {
      const startWpt = item.waypoints[0];
      const endWpt = item.waypoints[item.waypoints.length - 1];

      const lineCoords = item.geojsonCoordinates || item.waypoints.map((w) => [w.lng, w.lat]);

      const features = [];

      if (lineCoords.length > 1) {
        features.push({
          type: "Feature",
          properties: {
            name: `${item.title} Line`,
            stroke: item.routeColor,
            strokeWidth: 6,
          },
          geometry: {
            type: "LineString",
            coordinates: lineCoords,
          },
        });
      }

      if (startWpt) {
        features.push({
          type: "Feature",
          properties: { name: `${startWpt.name} (Start)`, icon: "start" },
          geometry: {
            type: "Point",
            coordinates: [startWpt.lng, startWpt.lat],
          },
        });
      }

      if (endWpt && endWpt !== startWpt) {
        features.push({
          type: "Feature",
          properties: { name: `${endWpt.name} (End)`, icon: "end" },
          geometry: {
            type: "Point",
            coordinates: [endWpt.lng, endWpt.lat],
          },
        });
      }

      const geojson = {
        type: "FeatureCollection",
        features,
      };

      allTracks.push({
        id: item.id,
        title: item.title,
        description: item.description,
        destinationName: item.destinationName,
        routeColor: item.routeColor,
        distanceKm: item.distanceKm,
        estimatedMinutes: item.estimatedMinutes,
        speedLimitKmH: item.speedLimitKmH,
        maxGradientPercent: item.maxGradientPercent,
        isExternalOnly: item.isExternalOnly || false,
        waypoints: item.waypoints,
        geojson,
      });
    }
  }
}

const tsContent = `// AUTO-GENERATED FROM YAML CONFIGURATION FILES IN src/data/tracks/
// DO NOT EDIT THIS FILE DIRECTLY. EDIT THE YAML FILES IN src/data/tracks/ INSTEAD.

import type { FeatureCollection, LineString, Point } from "geojson";

export interface TrackWaypoint {
  name: string;
  lat: number;
  lng: number;
  instruction: string;
  type: "start" | "turn" | "checkpoint" | "end";
}

export interface Track {
  id: string;
  title: string;
  description: string;
  destinationName: string;
  routeColor: string;
  distanceKm: number;
  estimatedMinutes: number;
  speedLimitKmH: number;
  maxGradientPercent: number;
  isExternalOnly?: boolean;
  waypoints: TrackWaypoint[];
  geojson: FeatureCollection<LineString | Point>;
}

export const MOCK_TRACKS: Track[] = ${JSON.stringify(allTracks, null, 2)};
`;

fs.writeFileSync(outputFile, tsContent, "utf8");
console.log(`Successfully compiled ${allTracks.length} tracks from ${files.length} YAML files in src/data/tracks/`);
